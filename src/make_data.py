"""Generate a synthetic transfer market with a hidden fee formula.

Everything is a deterministic function of ``config.SEED``, so the CSV can be
regenerated byte-identically. The true pricing model lives in
``hidden_log_fee`` below and is never exposed to the feature pipeline.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from src import config as C


def _players(rng: np.random.Generator) -> pd.DataFrame:
    """A static pool of players with a latent ability level."""
    pos_p = np.array([0.22, 0.11, 0.11, 0.10, 0.16, 0.08, 0.07, 0.07, 0.06, 0.02])
    return pd.DataFrame(
        {
            "player_id": np.arange(1, C.N_PLAYERS + 1),
            "birth_year": rng.integers(1988, 2003, C.N_PLAYERS),
            "position": rng.choice(C.POSITIONS, size=C.N_PLAYERS, p=pos_p),
            "ability": np.clip(rng.normal(1.0, 0.28, C.N_PLAYERS), 0.15, 2.6),
            "origin_league": rng.choice(
                C.LEAGUES,
                size=C.N_PLAYERS,
                p=[0.28, 0.18, 0.17, 0.16, 0.11, 0.06, 0.04],
            ),
        }
    )


def _sample_transfer_events(rng: np.random.Generator, players: pd.DataFrame) -> pd.DataFrame:
    """Pick exactly ``N_TRANSFERS`` (player, season) events by career-stage weight.

    Young players move more often, so events repeat the same player_id across
    seasons the way a real career does.
    """
    seasons = np.arange(C.FIRST_SEASON, C.LAST_SEASON + 1)
    pl = players.reset_index(drop=True)

    season = np.tile(seasons, len(pl))
    age = season - np.repeat(pl["birth_year"].to_numpy(), len(seasons))

    active = (age >= 17) & (age <= 37)
    weight = np.where(active, 0.55 * np.exp(-0.5 * ((age - 25.0) / 6.0) ** 2) + 0.03, 0.0)
    weight = weight / weight.sum()

    idx = rng.choice(len(weight), size=C.N_TRANSFERS, replace=False, p=weight)
    events = pl.iloc[idx // len(seasons)].reset_index(drop=True)
    events["season"] = season[idx]
    events["age"] = age[idx]
    return events


def _destination_league(
    rng: np.random.Generator, origin: str
) -> str:
    """Most moves are a switch inside the same country; moves are up-weighted
    toward stronger leagues."""
    if rng.random() < 0.55:
        return origin
    pool = [lg for lg in C.LEAGUES if lg != origin]
    w = np.array([C.LEAGUE_STRENGTH[lg] ** 2.2 for lg in pool])
    return str(rng.choice(pool, p=w / w.sum()))


def _season_stats(rng: np.random.Generator, events: pd.DataFrame) -> pd.DataFrame:
    """Per-90 outputs and minutes played in the season *before* the move."""
    age = events["age"].to_numpy()
    ability = events["ability"].to_numpy()
    peak = np.exp(-0.5 * ((age - 25.5) / 4.5) ** 2)
    rating = ability * peak * rng.normal(1.0, 0.12, len(events))

    goals = np.clip(rating * 0.30 + rng.normal(0, 0.05, len(events)), 0.0, None)
    assists = np.clip(rating * 0.13 + rng.normal(0, 0.045, len(events)), 0.0, None)
    xg = np.clip(goals + rng.normal(0.0, 0.05, len(events)), 0.005, None)
    minutes = np.clip(rng.normal(1850, 720, len(events)), 240, 3960)

    return pd.DataFrame(
        {
            "goals_p90": np.round(goals, 3),
            "assists_p90": np.round(assists, 3),
            "xg_p90": np.round(xg, 3),
            "minutes": np.round(minutes).astype(int),
            "contract_years_left": np.round(
                np.clip(rng.gamma(2.2, 0.9, len(events)), 0.0, 5.0), 2
            ),
        },
        index=events.index,
    )


def hidden_log_fee(
    season: np.ndarray,
    age: np.ndarray,
    goals_p90: np.ndarray,
    assists_p90: np.ndarray,
    xg_p90: np.ndarray,
    contract_years_left: np.ndarray,
    position: np.ndarray,
    league: np.ndarray,
    noise: np.ndarray,
) -> np.ndarray:
    """The unobservable pricing rule. Peak value age sits around 24-27."""
    age_shape = np.exp(-0.5 * ((age - 25.0) / 5.5) ** 2) - 0.35
    league_strength = np.array([C.LEAGUE_STRENGTH[l] for l in league])
    position_prem = np.array([C.POSITION_PREMIUM[p] for p in position])

    return (
        C.LOG_BASE_FEE
        + 1.15 * age_shape
        + 1.05 * goals_p90
        + 0.85 * assists_p90
        + 0.55 * xg_p90
        + 0.30 * contract_years_left
        + 0.85 * league_strength
        + 0.45 * position_prem
        + np.log(C.YEARLY_INFLATION) * (season - C.BASE_SEASON)
        + noise
    )


def make_transfers(seed: int = C.SEED) -> pd.DataFrame:
    """Build the full synthetic transfer table."""
    rng = np.random.default_rng(seed)
    players = _players(rng)
    events = _sample_transfer_events(rng, players)
    stats = _season_stats(rng, events)

    df = pd.concat([events, stats], axis=1)
    df["league"] = [
        _destination_league(rng, o) for o in df["origin_league"].to_numpy()
    ]

    noise = rng.normal(0.0, C.FEE_NOISE_SIGMA, len(df))
    log_fee = hidden_log_fee(
        df["season"].to_numpy(),
        df["age"].to_numpy(),
        df["goals_p90"].to_numpy(),
        df["assists_p90"].to_numpy(),
        df["xg_p90"].to_numpy(),
        df["contract_years_left"].to_numpy(),
        df["position"].to_numpy(),
        df["league"].to_numpy(),
        noise,
    )

    # A club's pre-transfer valuation is a noisy read of the same fundamentals.
    mv_log = log_fee + rng.normal(0.0, C.MARKET_VALUE_NOISE_SIGMA, len(df))
    df["market_value_eur"] = (
        np.round(np.clip(np.exp(mv_log), 250_000, 220_000_000) / 10_000) * 10_000
    ).astype("int64")

    fee = np.round(np.clip(np.exp(log_fee), 250_000, 160_000_000) / 5_000) * 5_000
    df["fee_eur"] = fee.astype("int64")

    # Loans and free transfers: real rows that must be dropped before training.
    n_free = int(round(C.FREE_OR_LOAN_SHARE * len(df)))
    free_idx = rng.choice(len(df), size=n_free, replace=False)
    df["is_free_or_loan"] = False
    df.loc[free_idx, "fee_eur"] = 0
    df.loc[free_idx, "is_free_or_loan"] = True

    columns = [
        "player_id",
        "season",
        "age",
        "position",
        "league",
        "origin_league",
        "goals_p90",
        "assists_p90",
        "xg_p90",
        "minutes",
        "contract_years_left",
        "market_value_eur",
        "fee_eur",
        "is_free_or_loan",
    ]
    return df[columns].sort_values(["season", "player_id"]).reset_index(drop=True)


def write_transfers(path=None, seed: int = C.SEED) -> pd.DataFrame:
    path = C.RAW_CSV if path is None else path
    df = make_transfers(seed=seed)
    path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)
    return df


if __name__ == "__main__":
    data = write_transfers()
    print(f"wrote {len(data)} transfers -> {C.RAW_CSV}")
    print(data.head())